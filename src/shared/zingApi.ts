import type { EventChannel, EventContract, InvokeChannel, InvokeContract, Unsubscribe, ZingApi } from './ipc'

export type Invoke = <C extends InvokeChannel>(channel: C, ...args: InvokeContract[C]['args']) => Promise<InvokeContract[C]['result']>
export type Listen = <C extends EventChannel>(channel: C, listener: (payload: EventContract[C]) => void) => Unsubscribe

/**
 * The renderer's whole view of the host, built over a transport (WebView2's
 * chrome.webview messaging, `bridge/webviewBridge.ts`). A plain table of methods
 * onto channels; behaviour around every call, such as reporting failures
 * (`bridge/reportingInvoke.ts`), belongs in the `invoke` passed in.
 */
export function createZingApi(invoke: Invoke, listen: Listen): ZingApi {
	return {
		runCommand: (id) => invoke('command:run', id),
		getTabs: () => invoke('tabs:get'),
		activateTab: (id) => invoke('tabs:activate', id),
		closeTab: (id) => invoke('tabs:close', id),
		navigateTab: (id, url) => invoke('tabs:navigate', id, url),
		openLinkInNewTab: (url) => invoke('tabs:open-link', url),
		moveTab: (id, index) => invoke('tabs:move', id, index),
		pinTab: (id) => invoke('tabs:pin', id),
		unpinTab: (id) => invoke('tabs:unpin', id),
		openSavedTab: (itemId) => invoke('tabs:open-item', itemId),
		splitWith: (id, other) => invoke('split:with', id, other),
		splitDrop: (target, dropped, edge) => invoke('split:drop', target, dropped, edge),
		removeFromSplit: (id) => invoke('split:remove', id),
		setSplitDropZone: (zone) => invoke('split:drop-zone', zone),
		setSplitRatios: (splitId, ratios, length) => invoke('split:ratios', splitId, ratios, length),
		saveTab: (id, folderId, at) => invoke('tabs:save', id, folderId, at),
		moveStack: (key, index) => invoke('tabs:move-stack', key, index),
		moveWithinStack: (id, key, index) => invoke('tabs:move-within', id, key, index),
		closeOtherTabs: (id) => invoke('tabs:close-others', id),
		setTabOrganization: (organization) => invoke('tabs:set-organization', organization),
		setTabDropdowns: (on) => invoke('tabs:set-dropdowns', on),
		toggleStack: (key, anchorX) => invoke('stack:toggle', key, anchorX),
		openStackForDrag: (key, anchorX) => invoke('stack:open-for-drag', key, anchorX),
		closeStack: () => invoke('stack:close'),
		currentStack: () => invoke('stack:current'),
		stackDragPresence: (source, inside) => invoke('stack:drag-presence', source, inside),
		openStackMenu: (key, anchor) => invoke('chrome:stack-menu', key, anchor),
		openStripMenu: (anchor) => invoke('chrome:strip-menu', anchor),
		setTitleBarColors: (colors) => invoke('chrome:titlebar-colors', colors),
		openAppMenu: (anchor) => invoke('chrome:app-menu', anchor),
		openTabMenu: (id, anchor) => invoke('chrome:tab-menu', id, anchor),
		openDefaultAppsSettings: () => invoke('default-browser:open-settings'),
		openHistoryMenu: (direction, anchor) => invoke('chrome:history-menu', direction, anchor),
		getPageUi: () => invoke('pageui:get'),
		setPageUiHeight: (height) => invoke('pageui:height', height),
		getAccountPicker: () => invoke('pageui:picker-get'),
		setAccountPickerHeight: (height) => invoke('pageui:picker-height', height),
		closeAccountPicker: () => invoke('pageui:picker-close'),
		onAccountPicker: (listener) => listen('pageui:account-picker', listener),
		updateFind: (text) => invoke('find:update', text),
		stepFind: (direction) => invoke('find:step', direction),
		closeFind: () => invoke('find:close'),
		openDownload: (id) => invoke('downloads:open', id),
		showDownload: (id) => invoke('downloads:show', id),
		cancelDownload: (id) => invoke('downloads:cancel', id),
		clearDownloads: () => invoke('downloads:clear'),
		dismissDownloads: () => invoke('downloads:dismiss'),
		allowPermission: (id) => invoke('permission:allow', id),
		denyPermission: (id) => invoke('permission:deny', id),
		getLibrary: () => invoke('library:get'),
		applyLibrary: (action) => invoke('library:apply', action),
		openLibraryItem: (id, target) => invoke('library:open', id, target),
		openAllInFolder: (id) => invoke('library:open-all', id),
		setLibraryPanel: (panel) => invoke('library:panel', panel),
		openFolderMenu: (id, anchor) => invoke('library:folder-menu', id, anchor),
		openLibraryItemMenu: (id, anchor) => invoke('library:item-menu', id, anchor),
		getOverview: () => invoke('overview:get'),
		closeOverview: () => invoke('overview:close'),
		getSettings: () => invoke('settings:get'),
		setSetting: (key, value) => invoke('settings:set', key, value),
		onSettingsChanged: (listener) => listen('settings:changed', listener),
		getShell: () => invoke('shell:get'),
		openSettings: (category) => invoke('shell:open-settings', category),
		closeSettings: () => invoke('shell:close-settings'),
		openToolbox: () => invoke('shell:toolbox'),
		closeToolbox: () => invoke('shell:close-toolbox'),
		openShellMenu: (kind, id, anchor) => invoke('shell:menu', kind, id, anchor),
		clearBrowsingSession: () => invoke('shell:clear-session'),
		reportError: (report) => invoke('app:report-error', report),
		hashText: (text, algorithm) => invoke('hash:text', text, algorithm),
		hashFile: (token, algorithm) => invoke('hash:file', token, algorithm),
		hmac: (message, key, algorithm) => invoke('hash:hmac', message, key, algorithm),
		diagnose: (host) => invoke('net:diagnose', host),
		previewDns: () => invoke('dns:preview'),
		applyDns: (token) => invoke('dns:apply', token),
		undoDns: (token) => invoke('dns:undo', token),
		openLink: (input, runId) => invoke('relay:open', input, runId),
		allowRelayThirdParties: () => invoke('relay:allow-third-parties'),
		openRelayedTab: (url) => invoke('tabs:open-relayed', url),
		chooseOffer: (tool) => invoke('offer:choose', tool),
		dismissOffer: () => invoke('offer:dismiss'),
		onRelayAttempt: (listener) => listen('relay:attempt', listener),
		onShellState: (listener) => listen('shell:state', listener),
		getToolPanels: () => invoke('toolpanel:get'),
		openPanel: (content, at) => invoke('toolpanel:open', content, at),
		openPanelWithInput: (content, input) => invoke('toolpanel:open-with-input', content, input),
		closePanel: (id) => invoke('toolpanel:close', id),
		minimizePanel: (id) => invoke('toolpanel:minimize', id),
		restorePanel: (id) => invoke('toolpanel:restore', id),
		focusPanel: (id) => invoke('toolpanel:focus', id),
		beginPanelDrag: (id) => invoke('toolpanel:begin-drag', id),
		endPanelDrag: (id, origin) => invoke('toolpanel:end-drag', id, origin),
		onToolPanelsState: (listener) => listen('toolpanel:state', listener),
		listEngines: () => invoke('engines:list'),
		ensureEngine: (id) => invoke('engines:ensure', id),
		cancelEngine: (id) => invoke('engines:cancel', id),
		removeEngine: (id) => invoke('engines:remove', id),
		updateYtDlp: () => invoke('engines:update-ytdlp'),
		onEngineProgress: (listener) => listen('engines:progress', listener),
		runEngine: (engineId, panelId, job) => invoke('engines:run', engineId, panelId, job),
		cancelEngineJob: (jobId) => invoke('engines:cancel-job', jobId),
		savePage: () => invoke('page:save'),
		onEngineOutput: (listener) => listen('engines:output', listener),
		onEngineExit: (listener) => listen('engines:exit', listener),
		pickFiles: (kinds) => invoke('files:pick', kinds),
		copyFileToClipboard: (token) => invoke('files:copy-to-clipboard', token),
		printHtmlToPdf: (token, outputName) => invoke('convert:html-to-pdf', token, outputName),
		openToolSession: (panelId, token, kinds) => invoke('session:open', panelId, token, kinds),
		openSaveSession: (panelId, kinds) => invoke('session:open-save', panelId, kinds),
		openBackgroundPicture: (panelId, token) => invoke('bgremove:open', panelId, token),
		openDropped: (files) => invoke('files:open-dropped', files),
		openViewerFile: (token, panelId) => invoke('viewer:open', token, panelId),
		closeViewerFile: (id) => invoke('viewer:close', id),
		getAccount: () => invoke('account:get'),
		signUp: (username, displayName, email, password) => invoke('account:sign-up', username, displayName, email, password),
		signIn: (password) => invoke('account:sign-in', password),
		resetPassword: (password) => invoke('account:reset-password', password),
		signOut: () => invoke('account:sign-out'),
		continueAsGuest: () => invoke('account:continue-as-guest'),
		updateProfile: (displayName, email) => invoke('account:update-profile', displayName, email),
		setRequirePassword: (required) => invoke('account:require-password', required),
		deleteAccount: () => invoke('account:delete'),
		changePassword: (current, next) => invoke('account:change-password', current, next),
		onAccountState: (listener) => listen('account:state', listener),
		getVaultState: () => invoke('vault:get'),
		vaultSummaries: () => invoke('vault:summaries'),
		revealPassword: (id) => invoke('vault:reveal', id),
		revealOldPassword: (id, index) => invoke('vault:reveal-history', id, index),
		saveLogin: (login) => invoke('vault:save', login),
		updateLogin: (id, edit) => invoke('vault:update', id, edit),
		deleteLogin: (id) => invoke('vault:delete', id),
		restoreLogin: (id) => invoke('vault:restore', id),
		loginHistory: (id) => invoke('vault:history', id),
		copyPassword: (id) => invoke('vault:copy', id),
		importPasswordsCsv: (token) => invoke('vault:import-csv', token),
		exportPasswordsCsv: () => invoke('vault:export-csv'),
		neverSaves: () => invoke('vault:never-saves'),
		removeNeverSave: (origin) => invoke('vault:remove-never-save', origin),
		onVaultState: (listener) => listen('vault:state', listener),
		fillLogin: (pageId, id) => invoke('vault:fill', pageId, id),
		answerSaveLogin: (pageId, answer) => invoke('vault:answer-save', pageId, answer),
		getSyncState: () => invoke('sync:get'),
		signInToSync: () => invoke('sync:sign-in'),
		signOutOfSync: () => invoke('sync:sign-out'),
		cancelSyncSignIn: () => invoke('sync:cancel-sign-in'),
		turnOnSync: (password) => invoke('sync:turn-on', password),
		confirmRecoverySaved: () => invoke('sync:confirm-recovery-saved'),
		showRecoveryKey: () => invoke('sync:show-recovery'),
		uploadLocalCopy: () => invoke('sync:upload-local'),
		onSyncState: (listener) => listen('sync:state', listener),
		onTabsState: (listener) => listen('tabs:state', listener),
		onFocusAddress: (listener) => listen('chrome:focus-address', () => listener()),
		onStackDropdown: (listener) => listen('stack:dropdown', listener),
		onNotice: (listener) => listen('overlay:notice', listener),
		onPageUiState: (listener) => listen('pageui:state', listener),
		onLibraryState: (listener) => listen('library:state', listener),
		onOverview: (listener) => listen('overlay:overview', listener),
	}
}
