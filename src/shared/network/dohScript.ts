// Generates a PowerShell script that points the whole PC at a DNS-over-HTTPS
// resolver: Zing's replacement for Krackn's macOS .mobileconfig profile.
//
// The in-browser DoH only covers pages Zing loads. Windows 11's own DoH
// client covers every app and survives reboots, which is the supported OS
// mechanism. Changing it needs administrator rights, so Zing only writes the
// script; the user reads it and runs it themselves. An app quietly taking
// admin rights to change system networking is exactly what shouldn't happen.

export interface Resolver {
	name: string
	url: string
	addresses: string[]
	note: string
}

export const RESOLVERS: readonly Resolver[] = [
	{ name: 'Cloudflare', url: 'https://cloudflare-dns.com/dns-query', addresses: ['1.1.1.1', '1.0.0.1'], note: 'Fastest in most tests. No filtering.' },
	{ name: 'Cloudflare (malware blocking)', url: 'https://security.cloudflare-dns.com/dns-query', addresses: ['1.1.1.2', '1.0.0.2'], note: 'Same speed, but blocks known-malicious domains.' },
	{ name: 'Google', url: 'https://dns.google/dns-query', addresses: ['8.8.8.8', '8.8.4.4'], note: 'Very reliable, widely reachable.' },
	{ name: 'Quad9', url: 'https://dns.quad9.net/dns-query', addresses: ['9.9.9.9', '149.112.112.112'], note: 'Privacy-focused, blocks malicious domains.' },
]

// Windows 11 is build 22000; Windows 10 never got DoH outside Insider builds.
export const MIN_DOH_BUILD = 22000

// In a single-quoted PowerShell string only the quote itself is special, and
// it's escaped by doubling. Typographic quotes count as quotes too.
export function psQuote(text: string): string {
	return `'${text.replace(/['\u2018\u2019\u201a\u201b]/g, "''")}'`
}

export function displayTitle(resolver: Resolver, displayName?: string): string {
	const trimmed = displayName?.trim()
	return trimmed ? trimmed : `Encrypted DNS — ${resolver.name}`
}

export function makeEnableScript(resolver: Resolver, displayName?: string): string {
	const servers = resolver.addresses.map(psQuote).join(', ')
	return [
		'#Requires -RunAsAdministrator',
		`# ${displayTitle(resolver, displayName).replace(/[\r\n]+/g, ' ')}`,
		`# Routes DNS for this whole PC through ${resolver.name} over HTTPS.`,
		'# Generated by Zing. Read it before running it. Undo with the matching "disable" script.',
		"$ErrorActionPreference = 'Stop'",
		'',
		`if ([Environment]::OSVersion.Version.Build -lt ${MIN_DOH_BUILD}) {`,
		"\tthrow 'Encrypted DNS needs Windows 11 (build 22000 or later).'",
		'}',
		'',
		`$template = ${psQuote(resolver.url)}`,
		`$servers = @(${servers})`,
		'',
		'# Register each address with its HTTPS template. Windows already knows some',
		'# of these, in which case the existing entry is updated instead.',
		'foreach ($server in $servers) {',
		'\tif (Get-DnsClientDohServerAddress -ServerAddress $server -ErrorAction SilentlyContinue) {',
		'\t\tSet-DnsClientDohServerAddress -ServerAddress $server -DohTemplate $template -AllowFallbackToUdp $false -AutoUpgrade $true',
		'\t} else {',
		'\t\tAdd-DnsClientDohServerAddress -ServerAddress $server -DohTemplate $template -AllowFallbackToUdp $false -AutoUpgrade $true',
		'\t}',
		'}',
		'',
		'# Point every connected adapter at those addresses. AutoUpgrade makes',
		'# Windows use HTTPS for them; fallback to plain DNS is off.',
		"Get-NetAdapter | Where-Object Status -eq 'Up' | ForEach-Object {",
		'\tSet-DnsClientServerAddress -InterfaceIndex $_.ifIndex -ServerAddresses $servers',
		'}',
		'',
		`Write-Host ${psQuote(`Done. DNS now goes to ${resolver.name} over HTTPS.`)}`,
		'',
	].join('\r\n')
}

// Hands DNS back to whatever the network provides (DHCP). The DoH templates
// stay registered: they're inert unless an adapter uses those addresses.
export function makeDisableScript(): string {
	return [
		'#Requires -RunAsAdministrator',
		'# Restores automatic DNS on every connected adapter. Generated by Zing.',
		"$ErrorActionPreference = 'Stop'",
		"Get-NetAdapter | Where-Object Status -eq 'Up' | ForEach-Object {",
		'\tSet-DnsClientServerAddress -InterfaceIndex $_.ifIndex -ResetServerAddresses',
		'}',
		"Write-Host 'Done. DNS is automatic again.'",
		'',
	].join('\r\n')
}

const FORBIDDEN = /[<>:"/\\|?*]/g

export function scriptFileName(resolver: Resolver, displayName?: string): string {
	const base = displayName?.trim() ? displayName.trim() : `DoH-${resolver.name}`
	const printable = [...base].filter((ch) => ch.charCodeAt(0) >= 0x20).join('')
	const cleaned = printable.replace(FORBIDDEN, '').replace(/\s+/g, '-').replace(/[.-]+$/, '').slice(0, 120)
	return `${cleaned || 'DoH'}.ps1`
}

// WireGuard for Windows replaces wg-quick. Krackn's stance stays: an app
// can't be a VPN (that needs a server elsewhere), and the user runs these
// commands themselves from an admin terminal.
export interface VpnCommands {
	install: string
	up: string
	down: string
}

export function wireGuardCommands(configPath: string): VpnCommands {
	const tunnel = (configPath.split(/[\\/]/).pop() ?? '').replace(/\.conf$/i, '')
	const exe = '& "C:\\Program Files\\WireGuard\\wireguard.exe"'
	return {
		install: 'winget install --id WireGuard.WireGuard --exact',
		up: `${exe} /installtunnelservice ${psQuote(configPath)}`,
		down: `${exe} /uninstalltunnelservice ${psQuote(tunnel)}`,
	}
}
